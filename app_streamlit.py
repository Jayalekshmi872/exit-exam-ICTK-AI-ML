import streamlit as st
import tensorflow as tf
import numpy as np
from PIL import Image
from pathlib import Path

st.set_page_config(
    page_title="Bharatanatyam Mudra Recognition",
    page_icon="🙏",
    layout="centered"
)

MODEL_PATH = Path("/content/mudra_cnn.keras")

CLASS_NAMES = [
    "Musti",
    "Pataka",
    "Sikhara",
    "Simhamukha",
    "Trisula"
]


@st.cache_resource
def load_model():
    if not MODEL_PATH.is_file():
        raise FileNotFoundError(
            f"Model not found: {MODEL_PATH}. "
            "Upload mudra_cnn.keras to Colab."
        )

    return tf.keras.models.load_model(str(MODEL_PATH))


def preprocess_image(image, target_size):
    image = image.convert("RGB")
    image = image.resize(target_size)

    # Match this preprocessing to your model training.
    image_array = np.asarray(image, dtype=np.float32)
    image_array = np.expand_dims(image_array, axis=0)

    return image_array


def main():
    st.title("🙏 Bharatanatyam Mudra Recognition")

    st.write(
        "Upload an image to identify one of five "
        "Bharatanatyam mudras."
    )

    try:
        model = load_model()
    except Exception as e:
        st.error("Unable to load the trained CNN model.")
        st.exception(e)
        st.stop()

    input_shape = model.input_shape
    output_shape = model.output_shape

    if isinstance(input_shape, list) or isinstance(output_shape, list):
        st.error("This app requires a single-input, single-output model.")
        st.stop()

    if len(input_shape) != 4:
        st.error(f"Unexpected model input shape: {input_shape}")
        st.stop()

    if output_shape[-1] != len(CLASS_NAMES):
        st.error(
            f"Model outputs {output_shape[-1]} classes, "
            f"but {len(CLASS_NAMES)} class names were provided."
        )
        st.stop()

    height, width = input_shape[1:3]

    if height is None or width is None:
        st.error("The model requires fixed image dimensions.")
        st.stop()

    uploaded_file = st.file_uploader(
        "Choose a mudra image",
        type=["jpg", "jpeg", "png"]
    )

    if uploaded_file is None:
        st.info("Upload an image to get a prediction.")
        return

    try:
        image = Image.open(uploaded_file).convert("RGB")

        st.image(
            image,
            caption="Uploaded Mudra Image",
            use_container_width=True
        )

        processed = preprocess_image(image, (width, height))

        with st.spinner("Recognizing mudra..."):
            predictions = model.predict(processed, verbose=0)[0]

        if len(predictions) != len(CLASS_NAMES):
            st.error("Prediction output does not match the classes.")
            st.stop()

        if not np.all(np.isfinite(predictions)):
            st.error("The model returned invalid prediction values.")
            st.stop()

        index = int(np.argmax(predictions))
        confidence = float(predictions[index]) * 100

        st.success(f"Predicted Mudra: {CLASS_NAMES[index]}")
        st.metric("Confidence", f"{confidence:.2f}%")

        st.caption(
            "Confidence reflects the model's output and does "
            "not guarantee a correct prediction."
        )

        st.divider()
        st.subheader("Class Scores")

        for i in np.argsort(predictions)[::-1]:
            score = float(predictions[i])
            st.write(f"**{CLASS_NAMES[i]}: {score * 100:.2f}%**")
            st.progress(float(np.clip(score, 0.0, 1.0)))

    except Exception as e:
        st.error("An error occurred while processing the image.")
        st.exception(e)

    st.divider()
    st.caption("Built with TensorFlow, CNN and Streamlit.")


if __name__ == "__main__":
    main()





