def find_model_file(filename="mudra_cnn.keras", search_path="/content"):
    print(f"Searching for '{filename}' starting from '{search_path}'...")
    found_files = []
    for root, dirs, files in os.walk(search_path):
        if filename in files:
            full_path = os.path.join(root, filename)
            found_files.append(full_path)
            print(f"Found model at: {full_path}")

    if not found_files:
        print("\nCould not find the model file directly. Let's list everything in /content to see what is there:")
